def _generated_schemas() -> dict[str, Any]:
    """Schema components straight out of the pydantic models."""
    _, defs = models_json_schema(
        [
            (DecideRequest, "validation"),
            (DecideResponse, "validation"),
            (Profile, "validation"),
        ],
        ref_template="#/components/schemas/{model}",
    )
    return defs["$defs"]


