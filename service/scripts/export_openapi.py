    """Overlay authored prose onto generated schemas, loudly.

    An overlay entry naming a schema or a field that the models no longer
    have raises: a renamed field must not leave a stale description behind.
    """
    unknown_schemas = sorted(set(SCHEMA_DESCRIPTIONS) - set(schemas))
    if unknown_schemas:
        raise RuntimeError(f"SCHEMA_DESCRIPTIONS names unknown schemas: {unknown_schemas}")
    for name, text in SCHEMA_DESCRIPTIONS.items():
        schemas[name]["description"] = text

    unknown_owners = sorted(set(FIELD_DESCRIPTIONS) - set(schemas))
    if unknown_owners:
        raise RuntimeError(f"FIELD_DESCRIPTIONS names unknown schemas: {unknown_owners}")
    for name, fields in FIELD_DESCRIPTIONS.items():
        properties = schemas[name].get("properties", {})
        unknown_fields = sorted(set(fields) - set(properties))
        if unknown_fields:
            raise RuntimeError(f"FIELD_DESCRIPTIONS[{name!r}] names unknown fields: {unknown_fields}")
        for field, text in fields.items():
            properties[field]["description"] = text


